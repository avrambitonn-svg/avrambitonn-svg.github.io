// Bundles the Edge Function "api" (api/index.ts + the server's modules it reuses) into one file,
// api/dist/index.js, so deploying is a single file. node:* stays external (Deno provides it).
// Two server modules are swapped for their Supabase versions: db/index.js (the store) and files.js (Storage).
import { build } from 'esbuild';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SERVER = resolve(here, '../../server/src');
const SWAP = new Map([
  [join(SERVER, 'db/index.js'), join(here, 'api/src/db.js')],
  [join(SERVER, 'files.js'), join(here, 'api/src/files.js')],
]);

const swapServerModules = {
  name: 'swap-server-modules',
  setup(b) {
    b.onResolve({ filter: /^\./ }, (args) => {
      if (!args.importer.startsWith(SERVER)) return undefined;
      const swapped = SWAP.get(resolve(args.resolveDir, args.path));
      return swapped ? { path: swapped } : undefined;
    });
  },
};

const result = await build({
  entryPoints: [join(here, 'api/index.ts')],
  outfile: join(here, 'api/dist/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['node:*'],
  inject: [join(here, 'api/src/shims.js')],
  plugins: [swapServerModules],
  banner: { js: '// Genair Ops - Edge Function "api". Generated by genair/supabase/functions/build.mjs: edit the sources, not this file.' },
  legalComments: 'none',
  metafile: true,
  logLevel: 'warning',
});

const inputs = Object.keys(result.metafile.inputs);
for (const bad of ['server/src/db/index.js', 'server/src/files.js', 'server/src/db/adapters.js', 'server/src/dbroutes.js']) {
  if (inputs.some((p) => p.endsWith(bad))) throw new Error(`the bundle must not contain ${bad}`);
}
const out = Object.values(result.metafile.outputs)[0];
console.log(`api/dist/index.js: ${(out.bytes / 1024).toFixed(0)} KB from ${inputs.length} modules`);
